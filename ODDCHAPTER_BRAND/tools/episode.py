"""
episode.py — Phase 12: the pipeline's gates, as executable checks.

  python3 tools/episode.py new   <slug> [--minutes 10] [--chapters 4]
  python3 tools/episode.py check <folder>

`new` scaffolds an episode folder from the templates, with word budgets computed at the measured
140 words/min. `check` reads the folder and tells you which gate you have not passed — the same
gates listed in 09_EPISODE_KIT/PIPELINE.md, so the document and the tool cannot drift.

Exit code 1 if any gate fails, so it can sit in a pre-publish hook.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
REPO = ROOT.parent
WPM = 140                      # measured from the reference read
KIT = ROOT / "09_EPISODE_KIT"

# not all runtime is speech: the title card and the sign-off/end card carry no VO
NON_VO_SECONDS = 35            # 5 s title card + 30 s signature & end card
SPLIT = {"cold_open": 0.08, "ending": 0.16}   # of the *speech* seconds


def mmss(seconds):
    return f"{int(seconds)//60}:{int(seconds)%60:02d}"


# ------------------------------------------------------------------ scaffold
def budgets(minutes, chapters):
    """Seconds first, words derived — so the beat sheet and the runtime agree."""
    speech = minutes * 60 - NON_VO_SECONDS
    cold_s = round(speech * SPLIT["cold_open"])
    end_s = round(speech * SPLIT["ending"])
    rest = speech - cold_s - end_s
    per_s = [rest // chapters] * chapters
    per_s[-1] += rest - sum(per_s)                    # absorb rounding in the last chapter
    w = lambda sec: round(sec * WPM / 60)
    return {"speech_seconds": speech, "total": w(speech), "cold_open": w(cold_s),
            "chapters": [w(x) for x in per_s], "ending": w(end_s),
            "seconds": {"cold_open": cold_s, "chapters": per_s, "ending": end_s}}


def scaffold(slug, minutes, chapters):
    safe = re.sub(r"[^a-z0-9]+", "-", slug.lower()).strip("-")
    ep_dir = REPO / "EPISODES" / f"EP_{safe}"
    if ep_dir.exists():
        print(f"refusing: {ep_dir} already exists")
        return 1
    b = budgets(minutes, chapters)
    for sub in ("01_SCRIPT", "02_VO", "03_ASSETS", "04_EDIT", "05_PUBLISH", "06_NOTES"):
        (ep_dir / sub).mkdir(parents=True, exist_ok=True)

    (ep_dir / "episode.json").write_text(json.dumps({
        "slug": safe, "minutes": minutes, "chapters": chapters, "wpm": WPM, "budgets": b,
    }, indent=2) + "\n")

    # beat sheet: real numbers, no placeholder arithmetic
    cold_end = b["cold_open"] / WPM * 60
    t = cold_end
    rows, cards = [], []
    for i, words in enumerate(b["chapters"], start=1):
        dur = words / WPM * 60
        rows.append(f"| Chapter {i} | {mmss(t)} → {mmss(t+dur)} | {int(dur)} s | {words} | "
                    f"`{i:02d}` — <TITLE> |")
        cards.append(f"{i:02d} — <TITLE>")
        t += dur
    end_dur = b["ending"] / WPM * 60
    rows.append(f"| Ending | {mmss(t)} → {mmss(t+end_dur)} | {int(end_dur)} s | {b['ending']} | — |")

    (ep_dir / "01_SCRIPT" / "beat_sheet.md").write_text(f"""# Beat sheet — <EPISODE TITLE>

Runtime {minutes}:00 · {WPM} words/min · VO budget **{b['total']} words** · {chapters} chapters
Generated by `tools/episode.py` — do not change the arithmetic by hand.

| Section | Time | Duration | Words | Chapter card copy |
|---|---|---|---|---|
| Cold open | 0:00 → {mmss(cold_end)} | {int(cold_end)} s | {b['cold_open']} | — |
{chr(10).join(rows)}

Title card after the cold open: 1.2 s build → title → signature once → cut.

## Per-beat rows

Fill one row per beat. Words in a section must sum to the budget above, ±5 %.

| # | Beat | Purpose | Words | Visual intention |
|---|---|---|---|---|
| 1 | | | | |

## Hook variants (write three, pick one)

| # | Opening line | Mechanism |
|---|---|---|
| A | | |
| B | | |
| C | | |
""")

    (ep_dir / "01_SCRIPT" / "evidence.md").write_text("""# Evidence sheet

Every factual claim in the film, with a source. A claim without a source is cut, not softened.

| # | Claim | Source | Date | Verified how |
|---|---|---|---|---|
| 1 | | | | |
""")

    (ep_dir / "01_SCRIPT" / "script.md").write_text("# Script — <EPISODE TITLE>\n\n"
                                                    "Written to the beat sheet. No line longer than "
                                                    "is comfortable to read aloud.\n")

    (ep_dir / "05_PUBLISH" / "metadata.md").write_text("""# Metadata

| Field | Value |
|---|---|
| Title (≤ 60 characters) | |
| Thumbnail headline (≤ 4 words) | |
| Description line 1 | |
| Description line 2 | |

## Chapters (start at 00:00, minimum 3)

```
00:00 <first chapter>
```
""")

    (ep_dir / "06_NOTES" / "decisions.md").write_text(
        "# Decisions\n\nWhat we chose, what we rejected, and why. One line each.\n")

    print(f"scaffolded {ep_dir.relative_to(REPO)}")
    print(f"  VO budget: {b['total']} words "
          f"(cold open {b['cold_open']} · chapters {b['chapters']} · ending {b['ending']})")
    return 0


# ------------------------------------------------------------------ checks
def words_in(path):
    text = path.read_text()
    text = re.sub(r"^#.*$", " ", text, flags=re.M)          # drop headings
    text = re.sub(r"`[^`]*`", " ", text)                     # drop code
    text = re.sub(r"[*_>|-]+", " ", text)                    # drop markdown furniture
    return len(re.findall(r"[A-Za-zÀ-ÿ0-9]+", text))


def image_size(path):
    out = subprocess.run(["identify", "-format", "%w %h", str(path)],
                         capture_output=True, text=True).stdout.split()
    return (int(out[0]), int(out[1])) if len(out) == 2 else None


def media_duration(path):
    out = subprocess.run(["python3", str(HERE / "audio_info.py"), str(path)],
                         capture_output=True, text=True).stdout
    m = re.search(r"(\d+\.\d+)\s*s", out)
    return float(m.group(1)) if m else None


def parse_srt(path):
    raw = path.read_text(encoding="utf-8", errors="replace").strip()
    blocks = re.split(r"\n\s*\n", raw)
    cues = []
    for b in blocks:
        lines = [ln for ln in b.splitlines() if ln.strip()]
        if len(lines) < 3:
            continue
        if not re.search(r"\d\d:\d\d:\d\d", lines[1]):
            continue
        text = lines[2:]
        cues.append(text)
    return cues


def check(folder):
    ep = Path(folder).resolve()
    ok = True
    results = []

    def gate(name, passed, detail=""):
        nonlocal ok
        ok = ok and passed
        results.append((name, passed, detail))

    meta = ep / "episode.json"
    plan = json.loads(meta.read_text()) if meta.exists() else None
    gate("episode.json", plan is not None, "plan and budgets" if plan else "missing — was this scaffolded?")

    ev = ep / "01_SCRIPT" / "evidence.md"
    if ev.exists():
        rows = [r for r in ev.read_text().splitlines()
                if r.strip().startswith("|") and "---" not in r and "Claim" not in r]
        filled = [r for r in rows if len([c for c in r.split("|")[2:-1] if c.strip()]) >= 4]
        gate("evidence sheet", len(filled) >= 1,
             f"{len(filled)} sourced claim(s)" if filled else "no row with claim + source + date")
    else:
        gate("evidence sheet", False, "01_SCRIPT/evidence.md missing")

    sc = ep / "01_SCRIPT" / "script.md"
    if sc.exists() and plan:
        n = words_in(sc)
        target = plan["budgets"]["total"]
        within = abs(n - target) <= target * 0.05
        gate("script word count", within and n > 50, f"{n} words vs {target} ±5 %")
    else:
        gate("script word count", False, "01_SCRIPT/script.md missing or not a plan")

    vo = list((ep / "02_VO").glob("*.wav")) + list((ep / "02_VO").glob("*.mp3"))
    if vo:
        durs = [(f.name, media_duration(f)) for f in vo]
        total = sum(d for _, d in durs if d)
        gate("voice-over", total > 0, f"{len(vo)} file(s), {total/60:.1f} min")
    else:
        gate("voice-over", False, "no .wav/.mp3 in 02_VO")

    thumbs = [p for p in (ep / "05_PUBLISH").glob("thumbnail*")
              if p.suffix.lower() in (".png", ".jpg", ".jpeg")]
    if thumbs:
        sz = image_size(thumbs[0])
        gate("thumbnail", sz == (1280, 720), f"{thumbs[0].name} {sz}")
    else:
        gate("thumbnail", False, "05_PUBLISH/thumbnail*.png missing")

    subs = list((ep / "04_EDIT").glob("*.srt"))
    if subs:
        cues = parse_srt(subs[0])
        long_lines = sum(1 for c in cues for ln in c if len(ln) > 42)
        too_many = sum(1 for c in cues if len(c) > 2)
        gate("subtitles", bool(cues) and long_lines == 0 and too_many == 0,
             f"{len(cues)} cues · {too_many} over 2 lines · {long_lines} over 42 chars")
    else:
        gate("subtitles", False, "no .srt in 04_EDIT")

    masters = list((ep / "05_PUBLISH").glob("*.mp4"))
    if masters:
        mb = masters[0].stat().st_size / 1e6
        gate("master", mb > 5, f"{masters[0].name} {mb:.0f} MB — existence only, dimensions not verified")
    else:
        gate("master", False, "no .mp4 in 05_PUBLISH")

    md = (ep / "05_PUBLISH" / "metadata.md")
    if md.exists():
        text = md.read_text()
        title = re.search(r"\|\s*Title.*?\|\s*([^|]*)\|", text)
        tval = (title.group(1).strip() if title else "")
        has_ch = "00:00" in text
        gate("metadata", 0 < len(tval) <= 60 and has_ch,
             f"title {len(tval)} chars · chapters {'yes' if has_ch else 'missing 00:00'}")
    else:
        gate("metadata", False, "05_PUBLISH/metadata.md missing")

    print(f"\n{ep.name}")
    for name, passed, detail in results:
        print(f"  [{'PASS' if passed else 'FAIL'}] {name:18} {detail}")
    print()
    if ok:
        print("ALL GATES PASS — structural only. Files, budgets and subtitle shape were checked;")
        print("this tool cannot judge the film, the mix or whether a claim is true.")
    else:
        print("NOT READY — fix the FAILs above")
    return 0 if ok else 1


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    cmd = argv[1]
    if cmd == "new":
        if len(argv) < 3:
            print("usage: episode.py new <slug> [--minutes 10] [--chapters 4]")
            return 2
        minutes, chapters = 10, 4
        if "--minutes" in argv:
            minutes = int(argv[argv.index("--minutes") + 1])
        if "--chapters" in argv:
            chapters = int(argv[argv.index("--chapters") + 1])
        return scaffold(argv[2], minutes, chapters)
    if cmd == "check":
        if len(argv) < 3:
            print("usage: episode.py check <folder>")
            return 2
        return check(argv[2])
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
